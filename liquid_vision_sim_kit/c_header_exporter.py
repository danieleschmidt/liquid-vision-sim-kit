"""
C Header Exporter

Exports model weight matrices as a C header file suitable for embedded
deployment (e.g. ARM Cortex-M, ESP32). Each weight array becomes a
const float array in the generated header.
"""

import numpy as np
from pathlib import Path
from typing import Any


class CHeaderExporter:
    """
    Export a model dict as a C header file with float32 weight arrays.

    Example
    -------
    >>> exporter = CHeaderExporter()
    >>> model = {"W_in": np.eye(4), "W_out": np.zeros((1, 4))}
    >>> exporter.export(model, "/tmp/model_weights.h")
    """

    def export(self, model_dict: dict[str, Any], filename: str) -> None:
        """
        Write weight matrices to a C header file.

        Parameters
        ----------
        model_dict : dict
            Maps weight names → array-like values.
        filename : str or Path
            Output .h file path.
        """
        path = Path(filename)
        guard = path.stem.upper().replace("-", "_").replace(".", "_") + "_H"
        lines = []

        lines.append(f"/* Auto-generated by CHeaderExporter - liquid-vision-sim-kit */")
        lines.append(f"#ifndef {guard}")
        lines.append(f"#define {guard}")
        lines.append("")
        lines.append("#include <stdint.h>")
        lines.append("")

        for name, value in model_dict.items():
            arr = np.asarray(value, dtype=np.float32).flatten()
            c_name = name.replace(".", "_").replace("-", "_")
            size = arr.size
            lines.append(f"/* {name}: {np.asarray(value).shape} */")
            lines.append(f"static const uint32_t {c_name}_size = {size};")
            lines.append(f"static const float {c_name}[{size}] = {{")

            # Format values in rows of 8
            row_width = 8
            for i in range(0, size, row_width):
                chunk = arr[i : i + row_width]
                formatted = ", ".join(f"{v:.8e}f" for v in chunk)
                comma = "," if (i + row_width) < size else ""
                lines.append(f"    {formatted}{comma}")
            lines.append("};")
            lines.append("")

        lines.append(f"#endif /* {guard} */")

        with open(path, "w", encoding="utf-8") as f:
            f.write("\n".join(lines) + "\n")
